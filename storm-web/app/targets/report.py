"""Self-contained HTML report for a target (FIREPOWER plan section P14.9).

Findings become a deliverable: one standalone HTML file, inline CSS, no CDN --
so a target's evidence trail can be handed over on its own.

P1.4: every rendered report carries an evidence signature trailer
(sha256 + HMAC-SHA256 over the exact bytes before the trailer). An exported
copy is verifiable via ``verify_render`` / POST /api/targets/report/verify.
"""
from __future__ import annotations

import html
import json
from typing import Any, Dict

from app.core.integrity import sign_content, verify_content

SIG_BEGIN = "<!-- EVIDENCE-SIGNATURE"

_CSS = """
body{font:14px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#0b0f14;color:#d7e0ea}
.wrap{max-width:900px;margin:0 auto;padding:32px}
h1{font-size:22px;margin:0 0 4px}h2{font-size:15px;text-transform:uppercase;letter-spacing:.08em;color:#7d8ea1;margin:28px 0 8px}
.meta{color:#8b9bb0;font-size:13px;margin-bottom:20px}
table{width:100%;border-collapse:collapse;font-size:13px}
th,td{text-align:left;padding:8px 10px;border-bottom:1px solid #1d2632;vertical-align:top}
th{color:#7d8ea1;font-weight:600}
code{background:#131a23;padding:2px 6px;border-radius:4px;font-size:12px;color:#9fd0ff}
.tag{display:inline-block;background:#132a1f;color:#5ee39b;border-radius:10px;padding:1px 9px;font-size:11px}
pre{background:#111922;padding:12px;border-radius:6px;overflow:auto;font-size:12px;color:#a9bdd4}
.empty{color:#7d8ea1;font-style:italic}
"""

def _esc(value: Any) -> str:
    return html.escape("" if value is None else str(value))

def render_html(target: Dict[str, Any]) -> str:
    findings = target.get("findings") or []
    rows = []
    for f in findings:
        evidence = f.get("evidence")
        ev = ("<pre>%s</pre>" % _esc(json.dumps(evidence, indent=2, sort_keys=True))
              if evidence else "")
        rows.append(
            "<tr><td><span class='tag'>%s</span></td><td>%s%s</td><td>%s</td></tr>"
            % (_esc(f.get("kind")), _esc(f.get("detail")), ev, _esc(f.get("created_at"))))
    body = ("".join(rows) if rows
            else "<tr><td colspan='3' class='empty'>no findings yet</td></tr>")

    doc = """<!doctype html>
<html><head><meta charset="utf-8"><title>Target %(name)s</title><style>%(css)s</style></head>
<body><div class="wrap">
<h1>Target: %(name)s</h1>
<div class="meta">host <code>%(host)s</code> &middot; created %(created)s &middot; updated %(updated)s
 &middot; %(n)d finding(s)</div>
<h2>Findings / evidence</h2>
<table><thead><tr><th>kind</th><th>detail</th><th>recorded</th></tr></thead>
<tbody>%(body)s</tbody></table>
<p class="meta">Generated by Storm-Breaker &middot; FIREPOWER target model (P14.9)</p>
</div></body></html>""" % {
        "name": _esc(target.get("name")),
        "host": _esc(target.get("host")),
        "created": _esc(target.get("created_at")),
        "updated": _esc(target.get("updated_at")),
        "n": len(findings),
        "body": body,
        "css": _CSS,
    }

    sig = sign_content(doc)
    return doc + "\n%s alg=%s sha256=%s signature=%s -->\n" % (
        SIG_BEGIN, sig["alg"], sig["sha256"], sig["signature"])

def verify_render(rendered: str) -> bool:
    """Verify an exported report: sign the bytes before the trailer, compare."""
    if not rendered or SIG_BEGIN not in rendered:
        return False
    doc, _, trailer = rendered.partition(SIG_BEGIN)
    # render placed "\n" between doc and trailer; sign the exact doc bytes
    if doc.endswith("\n"):
        doc = doc[:-1]
    # parse "alg=... sha256=... signature=..." out of the trailer
    import re
    m = re.search(r"alg=(\S+)\s+sha256=([0-9a-f]{64})\s+signature=([0-9a-f]+)",
                  trailer)
    if not m:
        return False
    integrity = {"alg": m.group(1), "sha256": m.group(2),
                 "signature": m.group(3)}
    return verify_content(doc, integrity)
